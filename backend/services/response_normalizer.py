# backend/services/response_normalizer.py
import datetime
from typing import Dict, Any, List, Optional
from backend.router.schemas import (
    AnalysisResponse,
    RoutingDecision,
    CompatibilityResult,
    ValidationResult,
    ImageMetadata,
    ExecutionStep,
    Evidence
)
from backend.services.evidence_service import EvidenceService

class ResponseNormalizer:
    @staticmethod
    def build_response(
        request_id: str,
        query: str,
        routing: RoutingDecision,
        compatibility: CompatibilityResult,
        metadata: List[ImageMetadata],
        execution_trace: List[ExecutionStep],
        model_result: Optional[Dict[str, Any]] = None,
        blocking_error: Optional[str] = None,
        validation: Optional[ValidationResult] = None,
        timings: Optional[Dict[str, float]] = None,
        routing_config: Optional[str] = None,
        total_duration_ms: float = 0.0
    ) -> AnalysisResponse:
        """
        Unifies and validates output across heterogeneous model architectures into
        a standardized research payload according to Section 7.
        """
        now_iso = datetime.datetime.now(datetime.timezone.utc).isoformat()
        timings_dict = timings or {"total_duration_ms": round(total_duration_ms, 2)}
        limitations: List[str] = []

        # Populate limitations based on domain rules
        if routing.detected_task.value in ("CHANGE_DETECTION", "CHANGE_VQA"):
            limitations.append("Detected image differences reflect computational change probabilities; field verification is required to confirm real-world events.")
        elif routing.detected_task.value == "OPTICAL_SAR_ANALYSIS":
            limitations.append("CROMA produces joint cross-modal contrastive representations. Embeddings require downstream classification heads for categorical land-cover labels.")
        elif routing.detected_task.value in ("SCENE_ANALYSIS", "CAPTIONING", "VQA"):
            limitations.append("Visual language interpretation is generated by a foundation model and should not be treated as independently verified ground truth.")

        # Add spatial alignment caveats if validation found discrepancies
        if validation and validation.warnings:
            for w in validation.warnings:
                if "Spatial" in w or "Dimension" in w or "co-registered" in w:
                    limitations.append(w)

        if blocking_error or not routing.is_executable:
            status = "rejected_incompatible" if "Change analysis requires" in str(blocking_error or routing.blocking_issue) else "unavailable"
            answer_text = blocking_error or routing.blocking_issue or "Pipeline execution could not proceed."

            return AnalysisResponse(
                request_id=request_id,
                query=query,
                task=routing.detected_task,
                task_type=routing.detected_task.value,
                input_type=routing.detected_input_type,
                modality=routing.detected_modality,
                status=status,
                answer=answer_text,
                models_used=[],
                selected_models=[],
                evidence=Evidence(text="Execution halted before model invocation; no empirical evidence produced."),
                confidence=None,
                router_confidence=routing.task_confidence,
                model_confidence=None,
                system_confidence=None,
                routing=routing,
                metadata=metadata,
                compatibility=compatibility,
                validation=validation,
                structured_task_spec=routing.structured_task_spec,
                limitations=limitations,
                execution_trace=execution_trace,
                timings=timings_dict,
                routing_config=routing_config,
                total_duration_ms=round(total_duration_ms, 2),
                timestamp=now_iso
            )

        # Successful model execution
        answer = model_result.get("answer", "Inference completed successfully.")
        model_confidence = model_result.get("confidence")  # None if model did not output it
        router_conf = routing.task_confidence
        sys_conf = round(0.5 * router_conf + 0.5 * model_confidence, 3) if model_confidence is not None else None

        raw_evidence = model_result.get("evidence", {})
        evidence = EvidenceService.normalize_evidence(
            raw_evidence=raw_evidence,
            task=routing.detected_task.value,
            supports_grounding=bool(raw_evidence.get("boxes")),
            supports_change_maps=bool(raw_evidence.get("change_mask_url"))
        )

        models_used = model_result.get("models_used") or ([routing.selected_model_name] if routing.selected_model_name else [])
        
        # selected_models records which models were nominated by routing,
        # while models_used strictly records which models genuinely completed execution
        nominated_models = [routing.selected_model_name] if routing.selected_model_name else []
        for plan_step in routing.execution_plan:
            for cand in ["ChangeStar", "GeoChat-7B", "CROMA", "RS-GroundingSpecialist"]:
                if cand in plan_step and cand not in nominated_models:
                    nominated_models.append(cand)

        return AnalysisResponse(
            request_id=request_id,
            query=query,
            task=routing.detected_task,
            task_type=routing.detected_task.value,
            input_type=routing.detected_input_type,
            modality=routing.detected_modality,
            status="success",
            answer=answer,
            models_used=models_used,
            selected_models=nominated_models,
            evidence=evidence,
            confidence=model_confidence,
            router_confidence=router_conf,
            model_confidence=model_confidence,
            system_confidence=sys_conf,
            routing=routing,
            metadata=metadata,
            compatibility=compatibility,
            validation=validation,
            structured_task_spec=routing.structured_task_spec,
            limitations=limitations,
            execution_trace=execution_trace,
            timings=timings_dict,
            routing_config=routing_config,
            total_duration_ms=round(total_duration_ms, 2),
            timestamp=now_iso
        )
